#!/usr/bin/env node
/* Builds src/sample-data.js (the built-in example text) from the raw Claude replies in
 * test-fixtures/sample-raw/. Prints every normalizer warning and alignment failure;
 * exits non-zero if there are any. Usage: node test-fixtures/build-sample.js */
'use strict';
const fs = require('fs');
const path = require('path');
const C = require('../src/core.js');

const ROOT = path.join(__dirname, '..');
const RAW = path.join(__dirname, 'sample-raw');
const readRaw = (name) => JSON.parse(fs.readFileSync(path.join(RAW, name + '.json'), 'utf8'));

const { egypt } = JSON.parse(fs.readFileSync(path.join(__dirname, 'texts.json'), 'utf8'));
const doc = C.buildDocument(egypt);
const overview = C.normalizeOverview(readRaw('overview'));

const STAMP = 1760659200000;
const analyses = {};
const chunkState = {};
let problems = 0;

for (const chunk of doc.chunks) {
  const sentences = chunk.sentenceIds.map((id) => doc.sentences.find((s) => s.id === id));
  const { analyses: a, warnings } = C.normalizeChunk(readRaw(chunk.id), sentences);
  for (const w of warnings) {
    problems++;
    console.log(`WARN ${chunk.id} ${w.id} [${w.kind}] ${w.msg_ar}`);
  }
  for (const s of sentences) {
    if (!a[s.id]) continue;
    if (!C.alignWords(s.text, a[s.id].words).ok) {
      problems++;
      console.log(`ALIGN ${chunk.id} ${s.id} failed`);
    }
    analyses[s.id] = a[s.id];
  }
  chunkState[chunk.id] = { status: 'done', error: '', warnings: [], changes_ar: [], reviewedAt: 0 };
}

const sample = {
  id: 'sample',
  isSample: true,
  course: 'translation',
  title: doc.title,
  paragraphs: doc.paragraphs,
  createdAt: STAMP,
  updatedAt: STAMP,
  doc,
  overview,
  overviewStatus: 'done',
  overviewError: '',
  chunkState,
  analyses,
  promptVersion: C.PROMPT_VERSION,
};

const out = `/* مُعرِب — built-in example text. Generated by test-fixtures/build-sample.js; do not edit by hand. */
window.MURIB_SAMPLE = ${JSON.stringify(sample, null, 1)};
`;
fs.writeFileSync(path.join(ROOT, 'src/sample-data.js'), out);
console.log(`sample-data.js: ${doc.sentences.length} sentences, ${doc.chunks.length} chunks, ${problems} problem(s)`);
process.exitCode = problems ? 1 : 0;
